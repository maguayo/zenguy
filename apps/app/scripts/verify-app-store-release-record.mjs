#!/usr/bin/env node

import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, lstatSync, readFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { validateReleaseRecord } from "./release-record-contract.mjs";

const appRoot = dirname(dirname(fileURLToPath(import.meta.url)));

function usage(exitCode = 2) {
  console.error(
    "usage: verify-app-store-release-record.mjs <release-record.json> " +
      "--screenshots-manifest <app-store-screenshots.json> " +
      "--smoke-test <release-smoke-test.md> --privacy-report <privacy-report.pdf> " +
      "--app-review-response <review-response-guideline-2.1.md> " +
      "--screen-recording <physical-device-recording.mov|mp4>",
  );
  process.exit(exitCode);
}

const args = process.argv.slice(2);
if (args[0] === "--") args.shift();
const recordArgument = args.shift();
if (recordArgument === undefined || recordArgument.startsWith("--")) usage();
const options = new Map();
while (args.length > 0) {
  const flag = args.shift();
  const value = args.shift();
  if (
    value === undefined ||
    ![
      "--app-review-response",
      "--privacy-report",
      "--screen-recording",
      "--screenshots-manifest",
      "--smoke-test",
    ].includes(flag ?? "") ||
    options.has(flag)
  ) {
    usage();
  }
  options.set(flag, value);
}
if (options.size !== 5) usage();

function regularFile(argument, label) {
  const path = resolve(argument);
  if (!existsSync(path)) throw new Error(`${label} does not exist: ${path}`);
  const stat = lstatSync(path);
  if (stat.isSymbolicLink() || !stat.isFile()) {
    throw new Error(`${label} must be a regular non-symlink file: ${path}`);
  }
  return { bytes: readFileSync(path), path, stat };
}

function digest(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

const recordFile = regularFile(recordArgument, "release record");
const screenshotsFile = regularFile(
  options.get("--screenshots-manifest"),
  "screenshots manifest",
);
const smokeFile = regularFile(options.get("--smoke-test"), "smoke-test record");
const privacyFile = regularFile(options.get("--privacy-report"), "privacy report");
const appReviewResponseFile = regularFile(
  options.get("--app-review-response"),
  "Guideline 2.1 response",
);
const screenRecordingFile = regularFile(
  options.get("--screen-recording"),
  "physical-device screen recording",
);
if (
  privacyFile.stat.size < 1_000 ||
  privacyFile.bytes.subarray(0, 5).toString("ascii") !== "%PDF-"
) {
  throw new Error(
    "privacy report must be a non-empty PDF; supply the report generated by Xcode",
  );
}
if (
  screenRecordingFile.stat.size < 1_000_000 ||
  screenRecordingFile.stat.size > 500_000_000 ||
  screenRecordingFile.bytes.subarray(4, 8).toString("ascii") !== "ftyp" ||
  !/\.(?:mov|mp4)$/u.test(screenRecordingFile.path)
) {
  throw new Error(
    "physical-device screen recording must be a 1-500 MB MOV/MP4 media file",
  );
}
if (appReviewResponseFile.stat.size > 100_000) {
  throw new Error("Guideline 2.1 response must remain under 100 KB");
}

const record = JSON.parse(recordFile.bytes.toString("utf8"));
const screenshotsManifest = JSON.parse(screenshotsFile.bytes.toString("utf8"));
const smokeTestSource = smokeFile.bytes.toString("utf8");
const appReviewResponseSource = appReviewResponseFile.bytes.toString("utf8");
let candidatePackageVersion;
let candidateAgeRatingConfig;
const repositoryFailures = [];

try {
  execFileSync("git", ["cat-file", "-e", `${record.candidate.commit}^{commit}`], {
    cwd: appRoot,
    stdio: "ignore",
  });
  const tagCommit = execFileSync(
    "git",
    ["rev-list", "-n", "1", `ios-v${record.candidate.version}`],
    { cwd: appRoot, encoding: "utf8" },
  ).trim();
  if (tagCommit !== record.candidate.commit) {
    repositoryFailures.push(
      "immutable iOS release tag does not point to the recorded commit",
    );
  }
  const candidatePackageJson = JSON.parse(
    execFileSync(
      "git",
      ["show", `${record.candidate.commit}:apps/app/package.json`],
      { cwd: appRoot, encoding: "utf8" },
    ),
  );
  candidateAgeRatingConfig = JSON.parse(
    execFileSync(
      "git",
      ["show", `${record.candidate.commit}:apps/app/app-age-rating.config.json`],
      { cwd: appRoot, encoding: "utf8" },
    ),
  );
  candidatePackageVersion = candidatePackageJson.version;
} catch {
  repositoryFailures.push(
    "recorded commit, immutable iOS release tag or candidate source is unavailable locally",
  );
}

for (const file of screenshotsManifest.files ?? []) {
  if (
    typeof file?.filename !== "string" ||
    basename(file.filename) !== file.filename ||
    !/^[0-9a-f]{64}$/u.test(file.sha256 ?? "") ||
    !Number.isSafeInteger(file.sizeBytes) ||
    file.sizeBytes <= 0 ||
    file.format !== "JPEG" ||
    file.hasAlpha !== false ||
    file.width !== 1320 ||
    file.height !== 2868
  ) {
    throw new Error("screenshots manifest contains an invalid file entry");
  }
  const screenshot = regularFile(
    join(dirname(screenshotsFile.path), file.filename),
    `screenshot ${file.filename}`,
  );
  if (
    screenshot.stat.size !== file.sizeBytes ||
    digest(screenshot.bytes) !== file.sha256 ||
    screenshot.bytes.subarray(0, 3).toString("hex") !== "ffd8ff"
  ) {
    throw new Error(`screenshot evidence does not match its manifest: ${file.filename}`);
  }
}

const failures = validateReleaseRecord(record, {
  ageRatingConfig: candidateAgeRatingConfig,
  appReviewResponseSha256: digest(appReviewResponseFile.bytes),
  appReviewResponseSource,
  packageVersion: candidatePackageVersion,
  privacyReportSha256: digest(privacyFile.bytes),
  screenRecordingFilename: basename(screenRecordingFile.path),
  screenRecordingSha256: digest(screenRecordingFile.bytes),
  screenshotsManifest,
  screenshotsManifestSha256: digest(screenshotsFile.bytes),
  smokeTestRecordSha256: digest(smokeFile.bytes),
  smokeTestSource,
});

failures.push(...repositoryFailures);

if (failures.length > 0) {
  for (const failure of failures) console.error(`FAIL: ${failure}`);
  process.exitCode = 1;
} else {
  console.log(
    `App Store release record verified for Zenguy ${record.candidate.version} ` +
      `(${record.candidate.build}), stage ${record.appReview.stage}.`,
  );
}
